/**
 * Theo end-to-end pipeline runner — the AUTONOMY milestone for the readiness loop.
 *
 * It does, unattended, what a client's device would do: read a spool of real
 * requests, reduce each one, and put the lossy (gated) candidate through the
 * replay gate, emitting a verdict and the measured saving. It reads a spool,
 * runs, writes evals/results/theo-pipeline.json, and exits 0 — no prompting.
 *
 *   node --import tsx evals/theo-pipeline-run.ts
 *   MESH_SPOOL=/path/to/requests.json node --import tsx evals/theo-pipeline-run.ts
 *
 * HONESTY — what this run does and does NOT prove:
 *   • It proves the PLUMBING: spool → reduce → replay gate → verdict → exit,
 *     with the token saving taken from each response's reported usage (measured,
 *     not projected), exactly as it would be against a real provider.
 *   • It does NOT prove QUALITY. The `call` here is a local, content-faithful
 *     stub whose usage equals the true token count of the prompt it is handed,
 *     so savings are real, but its "answer" is derived from the prompt rather
 *     than generated by a model. A quality verdict is only real when `call` is
 *     pointed at the customer's actual provider (an API key / endpoint). That
 *     is the one remaining seam, and it is a configuration, not more code.
 */
import { writeFileSync } from "node:fs";
import { readFileSync } from "node:fs";
import { approximateTokenCount, type TokenPrice } from "../packages/core/src/index.js";
import { reduceRequest } from "../packages/sdk-js/src/index.js";
import {
  replayGate,
  responseText,
  exactTextGrader,
  type ReplayCandidate,
} from "../packages/sdk-js/src/replay-gate.js";
import { sampleCodingWorkload } from "./theo-loop.js";

const PRICE: TokenPrice = {
  inputPerMillion: 2, outputPerMillion: 10, cachedInputPerMillion: 0.2, cacheWriteInputPerMillion: 2.5,
};

// --- The spool: real requests to run the pipeline over --------------------------
// A client device feeds Theo its own traffic. Here that is the recorded
// coding-agent sample by default, or a JSON array of request objects at MESH_SPOOL.
function loadSpool(): unknown[] {
  const path = process.env.MESH_SPOOL;
  if (path) {
    const parsed = JSON.parse(readFileSync(path, "utf8")) as unknown;
    if (!Array.isArray(parsed)) throw new Error(`MESH_SPOOL ${path} must be a JSON array of request objects.`);
    return parsed;
  }
  return sampleCodingWorkload().map((s) => s.request);
}

// --- The model seam -------------------------------------------------------------
// A content-faithful local stub: usage = the true token count of the prompt it
// is handed (so baseline vs candidate savings are REAL), and the "answer" is the
// request's answer-bearing content (system + the last user turn), which every
// shipping lever preserves. Swap this for a provider call to get a real quality
// verdict; the gate code does not change.
function promptText(request: unknown): string {
  return typeof request === "string" ? request : JSON.stringify(request);
}

function answerBearingContent(request: unknown): string {
  if (typeof request !== "object" || request === null) return promptText(request);
  const r = request as Record<string, unknown>;
  const system = typeof r.system === "string" ? r.system : "";
  let lastUser = "";
  const messages = Array.isArray(r.messages) ? r.messages : Array.isArray(r.input) ? r.input : [];
  for (const m of messages) {
    if (typeof m === "object" && m !== null && (m as Record<string, unknown>).role === "user") {
      const c = (m as Record<string, unknown>).content;
      lastUser = typeof c === "string" ? c : JSON.stringify(c);
    }
  }
  // The answer depends only on content a safe reduction keeps intact.
  return `${system}\n>>>${lastUser}`;
}

function localModel(request: unknown): Promise<unknown> {
  const inputTokens = approximateTokenCount(promptText(request));
  const answer = `answer::${approximateTokenCount(answerBearingContent(request))}::${answerBearingContent(request).slice(0, 80)}`;
  return Promise.resolve({ output_text: answer, usage: { input_tokens: inputTokens, output_tokens: 64 } });
}

type Caller = { provider: string; verifiesQuality: boolean; call: (request: unknown) => Promise<unknown> };

/**
 * Choose the model seam from the environment. With a real key/endpoint set, the
 * gate replays against the customer's own provider and the quality verdict is
 * real. With nothing set, it falls back to the local stub (plumbing only). This
 * is the ONE seam that turns the readiness pipeline from plumbing-proven into
 * quality-verified — and it is a configuration, not a code change.
 *
 *   MESH_REPLAY_ENDPOINT + MESH_REPLAY_API_KEY   POST the request as-is, Bearer auth
 *   ANTHROPIC_API_KEY                            Anthropic Messages API (claude-* models)
 *   (none)                                       local stub
 */
function makeCaller(): Caller {
  const endpoint = process.env.MESH_REPLAY_ENDPOINT;
  const endpointKey = process.env.MESH_REPLAY_API_KEY;
  if (endpoint && endpointKey) {
    return {
      provider: `custom-endpoint (${endpoint})`,
      verifiesQuality: true,
      call: async (request) => {
        const res = await fetch(endpoint, {
          method: "POST",
          headers: { "content-type": "application/json", authorization: `Bearer ${endpointKey}` },
          body: JSON.stringify(request),
          signal: AbortSignal.timeout(60_000),
        });
        if (!res.ok) throw new Error(`provider ${res.status}`);
        return await res.json();
      },
    };
  }
  const anthropicKey = process.env.ANTHROPIC_API_KEY;
  if (anthropicKey) {
    return {
      provider: "anthropic-messages",
      verifiesQuality: true,
      call: async (request) => {
        const res = await fetch("https://api.anthropic.com/v1/messages", {
          method: "POST",
          headers: {
            "content-type": "application/json",
            "x-api-key": anthropicKey,
            "anthropic-version": "2023-06-01",
          },
          body: JSON.stringify(request),
          signal: AbortSignal.timeout(60_000),
        });
        if (!res.ok) throw new Error(`anthropic ${res.status}`);
        return await res.json();
      },
    };
  }
  return { provider: "local-stub", verifiesQuality: false, call: localModel };
}

async function main(): Promise<void> {
  const requests = loadSpool();
  const candidates: ReplayCandidate[] = [
    { label: "lossless-auto", config: { toolSchemas: true, duplicateContext: true, repairCachePrefix: true } },
    {
      label: "gated-full",
      config: {
        toolSchemas: true, duplicateContext: true, repairCachePrefix: true,
        historyCompaction: true, crossTurnMemoryDedup: true, freshToolResultCap: true,
      },
    },
  ];

  const caller = makeCaller();
  const result = await replayGate({
    requests,
    call: caller.call,
    candidates,
    grade: exactTextGrader,
    maximumQualityDrop: 0.02,
    price: PRICE,
  });

  const qualityVerifiedAgainstRealModel = caller.verifiesQuality;
  const approved = result.approved;
  const out = {
    ranAt: new Date().toISOString(),
    spoolSize: requests.length,
    unattendedRun: true,
    provider: caller.provider,
    qualityVerifiedAgainstRealModel,
    providerCalls: result.calls,
    maximumQualityDrop: result.maximumQualityDrop,
    approvedCandidate: approved?.label ?? null,
    candidates: result.candidates.map((c) => ({
      label: c.label,
      approved: c.approved,
      meanQualityDelta: Number(c.meanQualityDelta.toFixed(4)),
      lower95QualityDelta: Number(c.lower95QualityDelta.toFixed(4)),
      tokenSavingPercent: Number(c.tokenSavingPercent.toFixed(2)),
      costSavingPercent: c.costSavingPercent === undefined ? null : Number(c.costSavingPercent.toFixed(2)),
      rejectionReason: c.rejectionReason ?? null,
    })),
    notes: [
      ...result.notes,
      qualityVerifiedAgainstRealModel
        ? `Quality verified against a real provider (${caller.provider}): savings AND answer-equivalence are both measured.`
        : "LOCAL STUB MODEL: token savings are measured and real; the quality verdict is plumbing-only. Set ANTHROPIC_API_KEY or MESH_REPLAY_ENDPOINT+MESH_REPLAY_API_KEY to verify quality — no code change.",
    ],
  };
  writeFileSync("evals/results/theo-pipeline.json", `${JSON.stringify(out, null, 2)}\n`, "utf8");

  console.log("=== THEO PIPELINE (end-to-end, unattended) ===\n");
  console.log(`spool: ${requests.length} request(s) · provider: ${caller.provider} · provider calls: ${result.calls}`);
  for (const c of out.candidates) {
    console.log(
      `  ${c.label.padEnd(14)} saving ${String(c.tokenSavingPercent).padStart(6)}%  ` +
        `quality Δ ${c.meanQualityDelta} (low95 ${c.lower95QualityDelta})  ${c.approved ? "APPROVED" : `rejected (${c.rejectionReason})`}`,
    );
  }
  console.log(`\napproved candidate: ${out.approvedCandidate ?? "none"}`);
  console.log(`quality verified against a REAL model: ${qualityVerifiedAgainstRealModel ? `yes (${caller.provider})` : "NO — local stub; set a provider call"}`);
  console.log("\nwrote evals/results/theo-pipeline.json");
}

void main();
